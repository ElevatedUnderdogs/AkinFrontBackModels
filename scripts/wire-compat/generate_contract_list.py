#!/usr/bin/env python3
"""Writes Tests/FrontBackModelsTests/WireCompat/WireContracts.generated.swift: every contract in Sources."""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parents[2]
aliases, contracts = set(), []
files = sorted(root.glob("Sources/**/*.swift"))
for f in files:
    for m in re.finditer(r"typealias\s+(\w+)\s*=\s*Request<", f.read_text()):
        aliases.add(m.group(1))
for f in files:
    lines = f.read_text().splitlines()
    current, depth = None, 0
    for line in lines:
        code = line.split("//")[0]
        if current is None:
            m = re.match(r"\s*(?:public\s+)?extension\s+(\w+)\s*(?:where[^{]*)?\{", code)
            if m and m.group(1) in aliases:
                current, depth = m.group(1), 0
            else:
                continue
        m = re.match(r"\s*public\s+static\s+var\s+(\w+)\s*:\s*Self\b", code)
        if m and depth == 1:
            contracts.append(f"{current}.{m.group(1)}")
        depth += code.count("{") - code.count("}")
        if depth <= 0:
            current = None

out = root / "Tests/FrontBackModelsTests/WireCompat/WireContracts.generated.swift"
body = "\n".join(f"        WireContract({c})," for c in sorted(set(contracts)))
out.write_text(f"""// Generated by scripts/wire-compat/generate_contract_list.py. Do not edit.
import StrongContractClient
@testable import AkinFrontBackModels

extension WireContract {{
    static let all: [WireContract] = [
{body}
    ]
}}
""")
print(f"{len(set(contracts))} contracts -> {out.relative_to(root)}", file=sys.stderr)
